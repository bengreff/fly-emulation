def on(toggles) -> bool:
    return toggles.get("structure_rules", "off") not in ("off", False, None)


def residual(values, rid, element) -> float:
    """A residual's value for one element (0 where the worm carries none)."""
    r = values.get(rid)
    if r is None:
        return 0.0
    try:
        return float(r[element])
    except (KeyError, IndexError):
        return 0.0


# --- chemical synapses -----------------------------------------------------------------------------------------
def chem_g_per_em_nS(p, rec_p, cls, nmj=False) -> float:
    """Conductance of one EM section of a pair's synapse for receptor class cls (None = the graded synapse), nS."""
    if cls is None:
        return float(p["nmj_graded_g_per_em_nS" if nmj else "syn_graded_g_per_em_nS"])
    return float(p[f"{'nmj' if nmj else 'syn'}_nchan_per_em_{cls}"]) * float(rec_p[f"rec_{cls}_gamma_pS"]) / 1000.0


def reshare(classes, alpha):
    """[(class, share)] with shares re-weighted to share^alpha (renormalised); alpha 1 returns them unchanged."""
    if alpha == 1.0 or len(classes) < 2:
        return classes
    w = [(c, s ** alpha if s > 0 else 0.0) for c, s in classes]
    tot = sum(x for _, x in w)
    return [(c, x / tot) for c, x in w] if tot > 0 else classes


