def receptor_sign(st, pre, post_cls, ratio=1.0):
    """(inhibitory 0/1, rule) for a pair with no measured or Fenyves sign: CeNGEN receptor TPM, else transmitter."""
    tr = st.transmitter.get(pre, set()) & set(SIGN_RECEPTORS)
    ex = sum(st.expr(g, post_cls) for t in tr for g in SIGN_RECEPTORS[t][0]) if post_cls else 0.0
    ih = sum(st.expr(g, post_cls) for t in tr for g in SIGN_RECEPTORS[t][1]) if post_cls else 0.0
    if ex + ih > 0:
        return int(ih > ratio * ex), "cengen"
    return int(st.transmitter.get(pre, set()) == {"gaba"}), "transmitter"


# --- gap junctions ---------------------------------------------------------------------------------------------
def innexin_weights(st, cls):
    """{innexin: TPM} expressed by a CeNGEN class (None = no class: unknown expression)."""
    if cls is None:
        return None
    return {g: x for g in INNEXINS if (x := st.expr(g, cls)) > 0}


def _side_sqrt_gamma(p, w):
    if not w:                                           # no class (or none expressed): every innexin alike
        return float(np.mean([math.sqrt(p[f"gap_unitary_{g.replace('-', '_')}_pS"]) for g in INNEXINS]))
    tot = sum(w.values())
    return sum(x * math.sqrt(p[f"gap_unitary_{g.replace('-', '_')}_pS"]) for g, x in w.items()) / tot


def gap_unitary_pS(p, wa, wb) -> float:
    """Expression-weighted unitary conductance of a junction's channels (pS)."""
    return _side_sqrt_gamma(p, wa) * _side_sqrt_gamma(p, wb)


def gap_g_per_em_nS(p, open_per_em, wa, wb) -> float:
    return float(open_per_em) * gap_unitary_pS(p, wa, wb) / 1000.0


# --- channel densities (FIT2 form) -----------------------------------------------------------------------------
def tpm_ref(st, gene) -> float:
    if gene not in st.gene_index:
        return 1.0
    v = st.tpm[st.gene_index[gene]]
    return float(np.median(v[v > 0])) if (v > 0).any() else 1.0


def nic_density(p, ch, m_k, tpm, ref) -> float:
    """FIT2's map for one guessed (channel, class) density, S/cm2."""
    b, C = float(p["dens_map_tpm_slope"]), float(p["dens_map_tpm_pseudocount"])
    f = ((tpm + C) / (ref + C)) ** b if b != 0.0 else 1.0
    return float(m_k) * 10.0 ** float(p[f"dens_map_log10_{ch}"]) * f


