"""Type-pair synapse strengths from the flyvis ensemble as connection rows for our model (fly2, s14).

Ben via the Director (DECISIONS 13 Oct 22:53, item 1): flyvis per-type-pair strengths as a separately
switched arm labelled "fitted (flyvis, task-trained)". In flyvis (Lappalainen et al. 2024) the input to a
cell of type t from a cell of type s is sign_s x n_syn x alpha_st x relu(V_s), so alpha_st is a voltage
gain per synapse (mV/mV), one value per type pair, fitted to an optic-flow task. This writes the ensemble
median (and quartiles) per pair, mapped to male-cns type selectors, to data/params/flyvis_pair_strength.csv,
read only by cell_type:all|optic_lobe_flyvis_pair_strength (lif._flyvis_pairs).

Mapping (as flyvis_rows.py, plus the photoreceptors): Am -> Am1, TmY9 -> TmY9a/b, T5a and Tm3 with their
_unclear variants; R1..R6 -> R1-R6 with alpha the median over the collapsed pairs (derived); R7 -> R7d/p/y,
R8 -> R8d/p/y. Mi3, Mi11, Mi12 and Tm28 have no male-cns type and are dropped. CT1(M10) and CT1(Lo1) map to
the per-column compartments of cell_type:CT1|compartments_by_column (instance <cell>/M10|Lo1/<column>); with
that switch off their selectors match no cell and a point CT1 keeps the shared scale.

    uv run python scripts/vision/flyvis_pair_rows.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "data" / "derived" / "flyvis_lappalainen2024_edges.csv"
OUT = REPO / "data" / "params" / "flyvis_pair_strength.csv"
CITE = ("Lappalainen et al. 2024 Nature 634:1132 (doi 10.1038/s41586-024-07939-3); flyvis 1.2.0 ensemble "
        "flow/0000, 50 networks; data/derived/flyvis_lappalainen2024_edges.csv")
MAP = {"Am": "^Am1$", "TmY9": "^TmY9[ab]$", "T5a": "^T5a(?:_unclear)?$", "Tm3": "^Tm3(?:_unclear)?$",
       "R7": "^R7[dpy]$", "R8": "^R8[dpy]$", "R1-R6": "^R1-R6$"}
DROP = {"Mi3", "Mi11", "Mi12", "Tm28"}
RS = [f"R{i}" for i in range(1, 7)]


def sel(t: str) -> str:
    if t.startswith("CT1"):   # flyvis CT1(M10) / CT1(Lo1): the compartments of connectome.ct1_compartments
        return "instance:^CT1_[LR]/" + t[4:-1] + "/"
    return "type:" + MAP.get(t, f"^{t}$")


def main():
    e = pd.read_csv(SRC)
    e = e[~e.source.isin(DROP) & ~e.target.isin(DROP)].copy()
    stats = ["alpha_median", "alpha_q25", "alpha_q75"]
    # R1..R6 are one male-cns type: median over the flyvis pairs that collapse onto each pair (derived)
    e["rs"] = e.source.isin(RS) | e.target.isin(RS)
    e[["source", "target"]] = e[["source", "target"]].replace(dict.fromkeys(RS, "R1-R6"))
    assert (e.groupby(["source", "target"]).sign.nunique() == 1).all()
    e = e.groupby(["source", "target"], sort=False).agg(
        sign=("sign", "first"), n=("sign", "size"), rs=("rs", "any"), **{s: (s, "median") for s in stats}).reset_index()
    ct1 = e.source.str.startswith("CT1") | e.target.str.startswith("CT1")
    rows = pd.DataFrame({
        "pre": e.source.map(sel), "post": e.target.map(sel), "alpha": e.alpha_median.round(7),
        "alpha_q25": e.alpha_q25.round(7), "alpha_q75": e.alpha_q75.round(7), "flyvis_sign": e.sign.astype(int),
        "flyvis_pair": e.source + "->" + e.target, "use": 1,
        "basis": "inferred", "method": "fitted (flyvis, task-trained)",
        "note": np.where(e.rs, "R1..R6 collapsed: median over " + e.n.astype(str) + " flyvis R1..R6 pairs (derived from fitted)",
                         np.where(ct1, "CT1 compartment: matches cells only with cell_type:CT1|compartments_by_column = 1", ""))})
    head = ("# flyvis type-pair strengths (fitted, task-trained; NOT physiology). alpha: ensemble median voltage gain "
            "per synapse (mV/mV) with quartiles. Generated by scripts/vision/flyvis_pair_rows.py; " + CITE + "\n")
    OUT.write_text(head + rows.to_csv(index=False))
    print(f"{len(rows)} pairs ({int(ct1.sum())} CT1 compartment pairs) -> {OUT}")


if __name__ == "__main__":
    main()
